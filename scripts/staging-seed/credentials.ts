/**
 * The seed's private credentials file: the only place new accounts' passwords
 * are kept. It is reserved before the seed connects to anything, and each
 * password is saved in it before the account that uses it is created, so an
 * interrupted apply never loses a password and a resumed one reuses it.
 *
 * Format (JSON, mode 0600, outside the repository):
 *   { format, version, fileId, seed, target: { kind, projectId }, planDigest,
 *     accounts: { [uid]: { email, password, status, runId, savedAt } } }
 * status is "pending" (saved, account not yet confirmed) or "created" (the
 * seed created the account and recorded it in its ledger). runId tells
 * which run generated a password. fileId is random; the seed's ledger
 * records it (never a password) beside each account, so it is clear which
 * file holds which account's password.
 *
 * Writes. Every write goes to a new temporary file, written in full (a loop
 * that advances by the bytes actually written and fails on no progress),
 * flushed, and only then moved into place: a new file by link(), which never
 * replaces an existing one, and an update by rename(). A crash or failure
 * therefore leaves either the previous or the new contents, never a partial
 * file. A failed write throws, which stops apply before the next account is
 * created. Error messages never include a password.
 *
 * One writer. While a session has the file open it holds `<file>.lock`,
 * created atomically (O_EXCL) before the file is created or read, and
 * removed by close() only if it still carries this session's token. A second
 * open or resume of the same file is refused. Before each update the session
 * also checks that it still holds the lock and that the file is exactly what
 * it last wrote. A killed process leaves its lock behind; recovering it is
 * explicit (recoverStaleLock) and refused unless the lock names a process on
 * this host that no longer exists. See docs/architecture/staging.md.
 */
import { randomBytes } from "node:crypto";
import * as nodeFs from "node:fs";
import { hostname } from "node:os";
import { basename, dirname, join, resolve, sep } from "node:path";
import type { SeedUser } from "./dataset";
import type { CredentialStore, SeedTargetInfo } from "./seed";

export const CREDENTIALS_FORMAT = "devtalk-staging-seed-credentials";
const VERSION = 1;
const LOCK_FORMAT = "devtalk-staging-seed-credentials-lock";

export interface CredentialsIdentity {
  seed: string;
  target: SeedTargetInfo;
  planDigest: string;
  /** The planned accounts; entries for anything else make a file invalid. */
  users: readonly SeedUser[];
}

interface Entry {
  email: string;
  password: string;
  status: "pending" | "created";
  runId: string;
  savedAt: string;
}

interface CredentialsFile {
  format: string;
  version: number;
  fileId: string;
  seed: string;
  target: SeedTargetInfo;
  planDigest: string;
  accounts: Record<string, Entry>;
}

interface LockOwner {
  format: string;
  token: string;
  pid: number;
  host: string;
  startedAt: string;
}

export class CredentialsFileError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "CredentialsFileError";
  }
}

/** The file operations used; tests substitute failing ones. */
export type FileOps = Pick<
  typeof nodeFs,
  | "openSync"
  | "writeSync"
  | "fsyncSync"
  | "closeSync"
  | "renameSync"
  | "linkSync"
  | "unlinkSync"
  | "readFileSync"
  | "lstatSync"
  | "statSync"
  | "realpathSync"
>;

/** Whether a process exists on this host: "alive", "gone", or "unknown" (e.g. it belongs to another user). */
export type ProcessProbe = (pid: number) => "alive" | "gone" | "unknown";

export interface OpenOptions {
  /** Continue with an existing file instead of reserving a new one. */
  resume: boolean;
  /** The repository root; the file must be outside it. */
  repoRoot: string;
  /**
   * Remove a lock left by a process that no longer exists before opening.
   * Refused unless the lock names a process on this host that is gone.
   */
  recoverStaleLock?: boolean;
  fs?: FileOps;
  makePassword?: () => string;
  probeProcess?: ProcessProbe;
}

export interface CredentialsSummary {
  path: string;
  /** The file's id, as recorded in the seed's ledger. */
  fileId: string;
  /** Accounts the seed created and confirmed, whose passwords are in this file. */
  created: number;
  /** Passwords saved for accounts not (yet) confirmed: interrupted or uncertain creation. */
  pending: number;
  /** Of the above, passwords generated by this run. */
  generatedThisRun: number;
}

export interface CredentialsFileStore extends CredentialStore {
  summary(): CredentialsSummary;
  /** Releases the writer lock (only if this session still holds it). Safe to call more than once. */
  close(): void;
}

const defaultProbe: ProcessProbe = (pid) => {
  try {
    process.kill(pid, 0);
    return "alive";
  } catch (error) {
    const code = (error as { code?: string })?.code;
    return code === "ESRCH" ? "gone" : "unknown";
  }
};

/** Writes every byte of data, advancing by what each write reports; no progress is a failure. */
export function writeAll(fs: FileOps, fd: number, data: Buffer) {
  let offset = 0;
  while (offset < data.length) {
    const written = fs.writeSync(fd, data, offset, data.length - offset);
    if (!Number.isInteger(written) || written <= 0 || written > data.length - offset) {
      throw new Error("write made no progress");
    }
    offset += written;
  }
}

/** Creates path exclusively (mode 0600), writes all of contents and flushes it. */
function writeNewFile(fs: FileOps, path: string, contents: string) {
  const fd = fs.openSync(path, "wx", 0o600);
  try {
    writeAll(fs, fd, Buffer.from(contents, "utf8"));
    fs.fsyncSync(fd);
  } finally {
    fs.closeSync(fd);
  }
}

function syncDirectory(fs: FileOps, dir: string) {
  const fd = fs.openSync(dir, "r");
  try {
    fs.fsyncSync(fd);
  } finally {
    fs.closeSync(fd);
  }
}

function removeQuietly(fs: FileOps, path: string) {
  try {
    fs.unlinkSync(path);
  } catch {
    // already gone
  }
}

function isInside(child: string, parent: string) {
  return child === parent || child.startsWith(parent.endsWith(sep) ? parent : parent + sep);
}

const serialize = (value: unknown) => `${JSON.stringify(value, null, 2)}\n`;

function validateFile(raw: unknown, identity: CredentialsIdentity): CredentialsFile | null {
  const file = raw as Partial<CredentialsFile> | null;
  if (typeof file !== "object" || file === null) return null;
  if (file.format !== CREDENTIALS_FORMAT || file.version !== VERSION || file.seed !== identity.seed) return null;
  if (typeof file.fileId !== "string" || !/^[0-9a-f]{32}$/.test(file.fileId)) return null;
  if (file.target?.kind !== identity.target.kind || file.target?.projectId !== identity.target.projectId) return null;
  if (file.planDigest !== identity.planDigest) return null;
  if (typeof file.accounts !== "object" || file.accounts === null || Array.isArray(file.accounts)) return null;
  const planned = new Map(identity.users.map((u) => [u.uid, u.email]));
  for (const [uid, entry] of Object.entries(file.accounts)) {
    if (planned.get(uid) === undefined || entry?.email !== planned.get(uid)) return null;
    if (typeof entry.password !== "string" || entry.password.length < 16) return null;
    if (entry.status !== "pending" && entry.status !== "created") return null;
  }
  return file as CredentialsFile;
}

function readLockOwner(fs: FileOps, lockPath: string): LockOwner | null {
  try {
    const owner = JSON.parse(fs.readFileSync(lockPath, "utf8") as string) as Partial<LockOwner>;
    if (owner?.format !== LOCK_FORMAT || typeof owner.token !== "string" || typeof owner.host !== "string") return null;
    if (!Number.isInteger(owner.pid) || (owner.pid as number) <= 0) return null;
    return owner as LockOwner;
  } catch {
    return null;
  }
}

const describeOwner = (owner: LockOwner | null) => (owner ? `process ${owner.pid} on ${owner.host} since ${owner.startedAt}` : "an unreadable lock");

/**
 * Removes a lock whose owner is provably gone: a readable lock, written on
 * this host, by a process that no longer exists. Anything else (alive,
 * another host, another user's process, unreadable) is refused. The lock is
 * moved aside and checked before it is deleted, so a lock taken over by
 * someone else in the meantime is put back rather than removed.
 */
function recoverLock(fs: FileOps, lockPath: string, probe: ProcessProbe) {
  try {
    fs.lstatSync(lockPath);
  } catch {
    return; // nothing to recover
  }
  const owner = readLockOwner(fs, lockPath);
  if (!owner) throw new CredentialsFileError(`cannot recover ${lockPath}: it is unreadable, so its owner is unknown; see the manual steps in docs/architecture/staging.md`);
  if (owner.host !== hostname()) throw new CredentialsFileError(`cannot recover ${lockPath}: it belongs to ${describeOwner(owner)}, another host`);
  const state = probe(owner.pid);
  if (state === "alive") throw new CredentialsFileError(`cannot recover ${lockPath}: ${describeOwner(owner)} is still running`);
  if (state !== "gone") throw new CredentialsFileError(`cannot recover ${lockPath}: cannot tell whether ${describeOwner(owner)} is still running`);

  const aside = `${lockPath}.stale-${randomBytes(4).toString("hex")}`;
  fs.renameSync(lockPath, aside);
  const moved = readLockOwner(fs, aside);
  if (moved?.token !== owner.token) {
    // Someone replaced the lock between our read and the rename: give it back
    try {
      fs.linkSync(aside, lockPath);
    } finally {
      removeQuietly(fs, aside);
    }
    throw new CredentialsFileError(`cannot recover ${lockPath}: it changed while being recovered`);
  }
  removeQuietly(fs, aside);
}

/**
 * Reserves a new credentials file (resume: false) or reopens one written for
 * the same seed, target and plan (resume: true), holding its writer lock
 * until close(). Throws CredentialsFileError, with the lock released and
 * nothing else written, if the file cannot be used.
 */
export function openCredentialsFile(path: string | undefined, identity: CredentialsIdentity, options: OpenOptions): CredentialsFileStore {
  const fs = options.fs ?? nodeFs;
  const makePassword = options.makePassword ?? (() => randomBytes(18).toString("base64url"));
  if (!path) throw new CredentialsFileError("a credentials file path is required");
  const full = resolve(path);
  const dir = dirname(full);

  let realDir: string;
  try {
    if (!fs.statSync(dir).isDirectory()) throw new Error("not a directory");
    realDir = fs.realpathSync(dir);
  } catch {
    throw new CredentialsFileError("the credentials file's directory does not exist");
  }
  const realRepo = fs.realpathSync(options.repoRoot);
  // The canonical path: the real directory plus the file name (the file itself may not exist yet)
  const finalPath = join(realDir, basename(full));
  if (isInside(finalPath, realRepo)) throw new CredentialsFileError("the credentials file must be outside the repository");
  const lockPath = `${finalPath}.lock`;
  const tempPath = () => join(realDir, `.${basename(finalPath)}.${process.pid}.${randomBytes(4).toString("hex")}.tmp`);

  // 1. Writer lock, before the file is created or read
  if (options.recoverStaleLock) recoverLock(fs, lockPath, options.probeProcess ?? defaultProbe);
  const owner: LockOwner = { format: LOCK_FORMAT, token: randomBytes(16).toString("hex"), pid: process.pid, host: hostname(), startedAt: new Date().toISOString() };
  let lockFd: number;
  try {
    lockFd = fs.openSync(lockPath, "wx", 0o600); // atomic: fails if any lock exists
  } catch (error) {
    if ((error as { code?: string })?.code === "EEXIST") {
      throw new CredentialsFileError(
        `the credentials file is in use by ${describeOwner(readLockOwner(fs, lockPath))} (${lockPath}). ` +
          "If that run was killed, re-run with --recover-stale-lock; see docs/architecture/staging.md"
      );
    }
    throw new CredentialsFileError("the credentials file's lock could not be created");
  }
  try {
    writeAll(fs, lockFd, Buffer.from(serialize(owner), "utf8"));
    fs.fsyncSync(lockFd);
  } catch {
    fs.closeSync(lockFd);
    removeQuietly(fs, lockPath); // created by this call (O_EXCL), so ours to remove
    throw new CredentialsFileError("the credentials file's lock could not be created");
  }
  fs.closeSync(lockFd);
  let held = true;
  const holdsLock = () => held && readLockOwner(fs, lockPath)?.token === owner.token;
  const release = () => {
    if (!held) return;
    held = false;
    if (readLockOwner(fs, lockPath)?.token === owner.token) removeQuietly(fs, lockPath);
  };

  // 2. Reserve or reopen the file (the lock is released if this fails)
  let file: CredentialsFile;
  let onDisk: string;
  try {
    if (!options.resume) {
      file = { format: CREDENTIALS_FORMAT, version: VERSION, fileId: randomBytes(16).toString("hex"), seed: identity.seed, target: { ...identity.target }, planDigest: identity.planDigest, accounts: {} };
      onDisk = serialize(file);
      reserve(fs, tempPath(), finalPath, realDir, onDisk);
    } else {
      ({ file, onDisk } = reopen(fs, finalPath, identity));
    }
  } catch (error) {
    release();
    throw error;
  }

  const runId = `${Date.now().toString(36)}-${randomBytes(4).toString("hex")}`;
  let generatedThisRun = 0;

  const save = (next: CredentialsFile) => {
    if (!holdsLock()) throw new CredentialsFileError("this session no longer holds the credentials file's lock; stopping before creating more accounts");
    let current: string;
    try {
      current = fs.readFileSync(finalPath, "utf8") as string;
    } catch {
      current = "";
    }
    if (current !== onDisk) throw new CredentialsFileError("the credentials file was changed outside this session; stopping before creating more accounts");

    const contents = serialize(next);
    const temp = tempPath();
    try {
      writeNewFile(fs, temp, contents);
      fs.renameSync(temp, finalPath);
    } catch {
      removeQuietly(fs, temp);
      throw new CredentialsFileError("the credentials file could not be updated; stopping before creating more accounts");
    }
    file = next;
    onDisk = contents;
    try {
      syncDirectory(fs, realDir);
    } catch {
      throw new CredentialsFileError("the credentials file was updated but could not be flushed; stopping before creating more accounts");
    }
  };

  const entryFor = (uid: string) => (Object.prototype.hasOwnProperty.call(file.accounts, uid) ? file.accounts[uid] : undefined);
  const open = () => {
    if (!held) throw new CredentialsFileError("the credentials file is closed");
  };

  return {
    id: file.fileId,
    passwordFor(user) {
      open();
      const existing = entryFor(user.uid);
      if (existing) {
        if (existing.email !== user.email) throw new CredentialsFileError(`the credentials file's entry for ${user.uid} names another email`);
        // The account is about to be created again (e.g. after cleanup): the same password, marked pending until confirmed
        if (existing.status === "created") {
          save({ ...file, accounts: { ...file.accounts, [user.uid]: { ...existing, status: "pending", savedAt: new Date().toISOString() } } });
        }
        return existing.password;
      }
      const entry: Entry = { email: user.email, password: makePassword(), status: "pending", runId, savedAt: new Date().toISOString() };
      save({ ...file, accounts: { ...file.accounts, [user.uid]: entry } });
      generatedThisRun++;
      return entry.password;
    },
    markCreated(uid) {
      open();
      const existing = entryFor(uid);
      if (!existing) throw new CredentialsFileError(`the credentials file has no entry for ${uid}`);
      if (existing.status === "created") return;
      save({ ...file, accounts: { ...file.accounts, [uid]: { ...existing, status: "created", savedAt: new Date().toISOString() } } });
    },
    summary() {
      const entries = Object.values(file.accounts);
      return {
        path: finalPath,
        fileId: file.fileId,
        created: entries.filter((e) => e.status === "created").length,
        pending: entries.filter((e) => e.status === "pending").length,
        generatedThisRun,
      };
    },
    close: release,
  };
}

/** Writes the complete initial file to a temporary path, then links it into place; link() never replaces an existing file. */
function reserve(fs: FileOps, temp: string, finalPath: string, realDir: string, contents: string) {
  try {
    writeNewFile(fs, temp, contents);
  } catch {
    removeQuietly(fs, temp);
    throw new CredentialsFileError("the credentials file could not be created");
  }
  try {
    fs.linkSync(temp, finalPath);
  } catch (error) {
    removeQuietly(fs, temp);
    throw new CredentialsFileError(
      (error as { code?: string })?.code === "EEXIST"
        ? "the credentials file already exists; pass --resume to continue with it, or choose a new path"
        : "the credentials file could not be created"
    );
  }
  removeQuietly(fs, temp);
  try {
    syncDirectory(fs, realDir);
  } catch {
    removeQuietly(fs, finalPath); // ours, created just now and holding no passwords
    throw new CredentialsFileError("the credentials file could not be created");
  }
}

function reopen(fs: FileOps, finalPath: string, identity: CredentialsIdentity) {
  let stat: nodeFs.Stats;
  try {
    stat = fs.lstatSync(finalPath);
  } catch {
    throw new CredentialsFileError("--resume needs an existing credentials file");
  }
  if (!stat.isFile()) throw new CredentialsFileError("the credentials file is not a regular file");
  if (stat.nlink !== 1) throw new CredentialsFileError("the credentials file has other hard links; use a file with a single path");
  if ((stat.mode & 0o077) !== 0) throw new CredentialsFileError("the credentials file is readable by other users; expected mode 0600");
  if (typeof process.getuid === "function" && stat.uid !== process.getuid()) throw new CredentialsFileError("the credentials file belongs to another user");
  let onDisk: string;
  let parsed: unknown;
  try {
    onDisk = fs.readFileSync(finalPath, "utf8") as string;
    parsed = JSON.parse(onDisk);
  } catch {
    throw new CredentialsFileError("the credentials file is not a seed credentials file");
  }
  const file = validateFile(parsed, identity);
  if (!file) throw new CredentialsFileError("the credentials file was written for another seed, target or plan");
  return { file, onDisk };
}
